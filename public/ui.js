// Avatar con iniciales y un tono estable derivado del nombre.
function avatar(name, size = '') {
  const str = String(name || '?');
  let h = 0;
  for (const ch of str) h = (h * 31 + ch.codePointAt(0)) % 360;
  const initials =
    str
      .trim()
      .split(/\s+/)
      .slice(0, 2)
      .map((w) => [...w][0])
      .join('')
      .toUpperCase() || '?';
  return `<span class="avatar ${size}" style="--h:${h}" aria-hidden="true">${esc(initials)}</span>`;
}

function toast(msg, type = 'error') {
  const el = document.createElement('div');
  el.className = `toast toast-${type}`;
  el.setAttribute('role', 'status');
  el.innerHTML = `${icon(type === 'error' ? 'alert' : 'checkCircle')}<span></span>`;
  el.querySelector('span').textContent = msg;
  document.body.appendChild(el);
  setTimeout(() => el.classList.add('out'), 3200);
  setTimeout(() => el.remove(), 3500);
}

// ---------------- Modales ----------------

const modalHead = (title, sub = '', ic = '') => `
  <div class="modal-head">
    <div class="modal-title">
      ${ic ? `<span class="modal-icon">${icon(ic)}</span>` : ''}
      <div><h2>${title}</h2>${sub ? `<p>${sub}</p>` : ''}</div>
    </div>
    <button class="btn btn-ghost btn-icon btn-sm" data-close aria-label="${t('close')}">${icon('x')}</button>
  </div>`;

function openModal(html, { onClose } = {}) {
  closeModal();
  const backdrop = document.createElement('div');
  backdrop.className = 'modal-backdrop';
  backdrop.id = 'modal';
  backdrop.innerHTML = `<div class="modal" role="dialog" aria-modal="true">${html}</div>`;
  backdrop._onClose = onClose;
  document.body.appendChild(backdrop);
  document.body.classList.add('modal-open');
  backdrop.addEventListener('mousedown', (e) => {
    if (e.target === backdrop) closeModal();
  });
  backdrop.querySelectorAll('[data-close]').forEach((b) => (b.onclick = () => closeModal()));
  const first = backdrop.querySelector('[autofocus]') || backdrop.querySelector('.modal-foot .btn-primary');
  if (first) first.focus();
  return backdrop;
}

function closeModal(result) {
  const m = document.getElementById('modal');
  if (!m) return;
  m.remove();
  document.body.classList.remove('modal-open');
  if (m._onClose) m._onClose(result);
}

// Sustituto de confirm(): devuelve una promesa con true si se acepta.
function confirmDialog({ title, body = '', confirmLabel = t('confirm'), danger = false }) {
  return new Promise((resolve) => {
    const m = openModal(
      `${modalHead(title, '', danger ? 'alert' : 'help')}
      ${body ? `<div class="modal-body"><p class="muted">${body}</p></div>` : ''}
      <div class="modal-foot">
        <button class="btn btn-secondary" data-close>${t('cancel')}</button>
        <button class="btn ${danger ? 'btn-danger' : 'btn-primary'}" data-ok>${confirmLabel}</button>
      </div>`,
      { onClose: (r) => resolve(r === true) }
    );
    const ok = m.querySelector('[data-ok]');
    ok.onclick = () => closeModal(true);
    ok.focus();
  });
}

